create table if not exists public.leads (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 name text not null check (char_length(name) between 1 and 100),
 email text not null check (char_length(email) between 3 and 200),
 company text, website text, industry text not null, service text not null,
 budget text, message text not null check (char_length(message) between 1 and 3000),
 source text not null default 'website',
 status text not null default 'new' check (status in ('new','contacted','qualified','closed'))
);
alter table public.leads enable row level security;
drop policy if exists "Public can submit leads" on public.leads;
create policy "Public can submit leads" on public.leads
 for insert to anon with check (
  char_length(name) between 1 and 100 and
  char_length(email) between 3 and 200 and
  char_length(message) between 1 and 3000
 );
-- Intentionally no public SELECT/UPDATE/DELETE policies: leads stay private.
